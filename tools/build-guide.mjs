#!/usr/bin/env node
/**
 * Compiles the canonical user-guide markdown (docs/user-guide/*.md) into
 * typed content modules bundled by the web and mobile apps:
 *   - web/src/guide-content.ts
 *   - mobile/src/guide-content.ts
 *
 * Front matter (--- title/audience/keywords ---) drives role filtering and
 * search. The body stays markdown; each app renders the small subset the
 * guide uses (#, ##, ###, -, numbered lists, **bold**, paragraphs).
 *
 * Run: npm run build:guide   (CI fails if the outputs are stale.)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const guideDir = path.join(repoRoot, 'docs', 'user-guide');

const pages = [];
for (const file of readdirSync(guideDir).filter((name) => name.endsWith('.md')).sort()) {
  const raw = readFileSync(path.join(guideDir, file), 'utf8');
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw);
  // Auxiliary documentation (e.g. coverage-checklist.md) has no front matter
  // and is not a guide page — skip it instead of failing the whole build.
  if (!match) continue;
  const meta = {};
  for (const line of match[1].split('\n')) {
    const idx = line.indexOf(':');
    if (idx > 0) meta[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
  }
  if (!meta.title || !meta.audience) throw new Error(`${file}: front matter needs title and audience`);
  pages.push({
    id: file.replace(/\.md$/, ''),
    title: meta.title,
    audience: meta.audience,
    keywords: meta.keywords ?? '',
    body: match[2].trim(),
  });
}

const header = `// GENERATED by tools/build-guide.mjs from docs/user-guide/*.md — do not edit by hand.
// Regenerate with: npm run build:guide
export type GuidePage = {
  id: string;
  title: string;
  audience: 'business' | 'platform' | 'all';
  keywords: string;
  body: string;
};

export const GUIDE_PAGES: GuidePage[] = ${JSON.stringify(pages, null, 2)};
`;

for (const target of ['web/src/guide-content.ts', 'mobile/src/guide-content.ts']) {
  writeFileSync(path.join(repoRoot, target), header, 'utf8');
  console.log(`✓ guide compiled -> ${target} (${pages.length} pages)`);
}
